import { randomBytes, pbkdf2Sync } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outDir = join(root, "src", "lib");
const outFile = join(outDir, "admin.env.ts");

const password = process.env.ADMIN_PASSWORD;
const enabled = Boolean(password);

let salt = randomBytes(16).toString("hex");
let hash;

if (enabled) {
  const derived = pbkdf2Sync(password, Buffer.from(salt, "hex"), 150000, 32, "sha256");
  hash = derived.toString("hex");
  console.log("[admin] key generated; panel ENABLED.");
} else {
  hash = randomBytes(32).toString("hex");
  console.warn("[admin] ADMIN_PASSWORD not set — admin panel DISABLED (fail closed).");
}

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// Auto-generated by scripts/gen-admin-key.mjs — do not edit.
export const ADMIN_ENABLED = ${enabled};
export const ADMIN_SALT = "${salt}";
export const ADMIN_HASH = "${hash}";
`,
  "utf8"
);